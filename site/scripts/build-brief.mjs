// Compact, reproducible overview projection; no independently maintained veto or tasks.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const site = resolve(import.meta.dirname, '..');
const base = resolve(site, 'assets/data/whoajor');
const pointer = JSON.parse(readFileSync(resolve(base, 'current.json')));
const root = resolve(base, pointer.version);
const manifest = JSON.parse(readFileSync(resolve(root, 'manifest.json')));
function rows(dataset) {
  return manifest.assets.filter(a => a.dataset === dataset).flatMap(a => JSON.parse(readFileSync(resolve(root, a.path))).rows);
}
const rosters = rows('rosters'), advice = rows('vetoAdvice');
const briefs = rows('recommendations').map(p => {
  const v = advice.find(a => a.opponentTeamId === p.opponentTeamId);
  const pick = v.ranking.find(r => r.map === p.verdict.pick);
  return { matchId: p.matchId, date: p.date, opponent: rosters.find(r => r.teamId === p.opponentTeamId).name,
    verdict: p.verdict, confidence: p.confidence, noAdvantage: pick.score <= 0,
    dataThrough: p.dataThrough, orderConfirmed: v.decisionTree.orderConfirmed,
    personalTasks: p.personalTasks, trainingChecklist: p.trainingChecklist };
});
const content = '// Generated by site/scripts/build-brief.mjs from the canonical snapshot.\nwindow.MATCH_BRIEFS = ' + JSON.stringify(briefs, null, 2) + ';\n';
const target = resolve(site, 'assets/js/data.brief.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== content) throw new Error('Overview brief is stale; run node site/scripts/build-brief.mjs');
} else writeFileSync(target, content);
